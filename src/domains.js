const byName = new Map();
for (const [domain, names] of Object.entries(assignments)) {
  for (const shortName of names.trim().split(/\s+/)) {
    const name = `ohos.permission.${shortName}`;
    if (byName.has(name)) throw new Error(`Duplicate permission domain assignment: ${name}`);
    byName.set(name, domain);
  }
}

/** Return the domain ID for a catalog record (or its full permission name).
 * Unknown records must be reviewed rather than silently assigned by a broad keyword.
 */
export function domainFor(permission) {
  const name = typeof permission === 'string' ? permission : permission?.name;
  const domain = byName.get(name);
  if (!domain) throw new Error(`Permission needs a reviewed business domain: ${name}`);
  return domain;
}
